"""Declarative base with deterministic constraint names.

Deterministic names matter for Alembic: dropping or altering a constraint in a
later migration requires knowing its name. Every table inherits this metadata.

Note: because the "ck" convention embeds %(constraint_name)s, every
CheckConstraint in the models MUST be given an explicit short name.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
